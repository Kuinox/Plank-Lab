                ReadConsumption.Consume(_read9.AsSpan(0, length));
                count += length;
            }
        }
        return count;
    }

    long ReadColumn(int ordinal)
        => ordinal switch
        {
            0 => ReadColumn0(),
            1 => ReadColumn1(),
            2 => ReadColumn2(),
            3 => ReadColumn3(),
            4 => ReadColumn4(),
            5 => ReadColumn5(),
            6 => ReadColumn6(),
            7 => ReadColumn7(),
            8 => ReadColumn8(),
            9 => ReadColumn9(),
            _ => throw new ArgumentOutOfRangeException(nameof(ordinal))
        };

    [Benchmark]
    public long Read()
    {
        _parallelism.Run(10, _columnWorkerCount,
            index => _columnCounts[index] = ReadColumn(index));
        long count = 0;
        for (var index = 0; index < 10; index++)
            count += _columnCounts[index];
        if (count != (long)Rows * 10)
            throw new InvalidDataException($"Expected {(long)Rows * 10} values, got {count}.");
        _readThreads = _parallelism.LastObserved;
        return count;
    }

    [GlobalCleanup]
    public void Cleanup()
    {
        if (_readThreads > 0)
            ColumnParallelism.WriteMarker(GetType().Name, "read", _columnWorkerCount, _readThreads);
        foreach (var reader in _columnReaders ?? [])
            reader?.Dispose();
        foreach (var source in _columnSources ?? [])
            source?.Dispose();
        _buffer?.Dispose();
        if (_pinned.IsAllocated) _pinned.Free();
    }
