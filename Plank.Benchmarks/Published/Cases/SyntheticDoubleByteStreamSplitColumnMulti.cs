    [Benchmark]
    public long Read()
    {
        _parallelism.Run(22, _columnWorkerCount,
            index => _columnCounts[index] = ReadColumn(index));
        long count = 0;
        for (var index = 0; index < 22; index++)
            count += _columnCounts[index];
        if (count != (long)Rows * 22)
            throw new InvalidDataException($"Expected {(long)Rows * 22} values, got {count}.");
        _readThreads = _parallelism.LastObserved;
        return count;
    }

    [GlobalCleanup]
    public void Cleanup()
    {
        if (_readThreads > 0)
            ColumnParallelism.WriteMarker("SyntheticDoubleByteStreamSplitColumnMultiParquetSharpBenchmarks", "read", _columnWorkerCount, _readThreads);
        foreach (var reader in _columnReaders ?? [])
            reader?.Dispose();
        foreach (var source in _columnSources ?? [])
            source?.Dispose();
        _buffer?.Dispose();
        if (_pinned.IsAllocated) _pinned.Free();
    }
