            ColumnParallelism.WriteMarker("SyntheticStringPlainColumnMultiParquetSharpBenchmarks", "read", _columnWorkerCount, _readThreads);
        foreach (var reader in _columnReaders ?? [])
            reader?.Dispose();
        foreach (var source in _columnSources ?? [])
            source?.Dispose();
        _buffer?.Dispose();
        if (_pinned.IsAllocated) _pinned.Free();
    }
