#!/usr/bin/env python3
"""Generates Plank.Fuzzing/RowFuzzEvolution.g.cs: a family of row schemas that differ from each other the
ways a schema evolves (columns added, removed, reordered, renamed, widened, required<->optional).
Any of them can be the file writer and any the reader (see RowEvolutionCases.cs).
Usage: python3 fuzz/tools/gen_row_evo.py > Plank.Fuzzing/RowFuzzEvolution.g.cs
"""
# class -> [(property, clr, column name, physical, optional)]
CLASSES = {
    "A": [("Seq", "int", "Seq"), ("A", "int", "A"), ("B", "long", "B"), ("C", "string", "C"), ("D", "int?", "D"), ("E", "double", "E")],
    "Old": [("Seq", "int", "Seq"), ("A", "int", "A"), ("B", "long", "B")],
    "Subset": [("Seq", "int", "Seq"), ("E", "double", "E"), ("B", "long", "B")],
    "Repet": [("Seq", "int", "Seq"), ("A", "int?", "A"), ("B", "long", "B"), ("C", "string", "C"), ("D", "int", "D"), ("E", "double", "E")],
    "Widen": [("Seq", "int", "Seq"), ("A", "long", "A"), ("B", "int", "B"), ("C", "string", "C"), ("D", "long?", "D"), ("E", "float", "E")],
    "Renamed": [("Seq", "int", "Seq"), ("A", "int", "A"), ("Beta", "long", "B"), ("C", "string", "C"), ("Gamma", "long", "Gamma"), ("E", "double", "E")],
}
PHYS = {"int": "Int32", "long": "Int64", "string": "ByteArray", "double": "Double", "float": "Float"}

def base(t): return t.rstrip("?")
def gen(t, name):
    b = base(t)
    e = {"int": "c.NextInt32()", "long": "c.NextInt64()", "string": "c.NextLabel()", "double": "c.NextDouble()",
         "float": "BitConverter.Int32BitsToSingle(c.NextInt32())"}[b]
    if t.endswith("?"):
        return f"c.NextInt(0, 3) == 0 ? null : ({t})({e})"
    return f"({b}){e}" if b != "string" else e

out = []
w = out.append
w("// <auto-generated by fuzz/tools/gen_row_evo.py; do not edit by hand. -->")
w("#nullable enable")
w("using Plank.Reading;")
w("using Plank.RowApi;")
w("using Plank.Schema;")
w("using Plank.Writing;")
w("")
w("namespace Plank.Fuzzing;")
w("")
names = []
for cls, cols in CLASSES.items():
    n = f"RowFuzzEvo{cls}"
    names.append((cls, n))
    w("[ParquetSchema(AllowAllocatingValues = true)]")
    w(f"public sealed partial class {n}")
    w("{")
    for prop, t, col in cols:
        attr = f'    [ParquetColumn("{col}")]\n' if col != prop else ""
        init = " = string.Empty;" if t == "string" else ""
        w(f"{attr}    public {t} {prop} {{ get; set; }}{init}")
    w("}")
    w("")
    w(f"sealed class {n}Evo : EvoClass")
    w("{")
    w(f'    internal override string Name => "{cls}";')
    w(f"    internal override string[] Props {{ get; }} = [{', '.join(chr(34) + p + chr(34) for p, _, _ in cols)}];")
    w(f"    internal override string[] ColumnNames {{ get; }} = [{', '.join(chr(34) + c + chr(34) for _, _, c in cols)}];")
    w(f"    internal override string[] Clr {{ get; }} = [{', '.join(chr(34) + t + chr(34) for _, t, _ in cols)}];")
    w(f"    internal override ParquetSchema Schema => {n}.Schema;")
    w("")
    w("    internal override object?[] Generate(ref PlankRowApiFuzzTarget.Cursor c, int seq)")
    w("        => [" + ", ".join("seq" if p == "Seq" else gen(t, p) for p, t, _ in cols) + "];")
    w("")
    w("    internal override byte[] Write(object?[][] rows, ParquetWriterOptions options)")
    w("    {")
    w("        using var stream = new MemoryStream();")
    w(f"        using (var w = {n}.CreateRowWriter(stream, options))")
    w("        {")
    w("            foreach (var cells in rows)")
    w("            {")
    w("                var row = w.GetRow();")
    for i, (p, t, _) in enumerate(cols):
        w(f"                row.{p} = ({t})cells[{i}]!;" if not t.endswith("?") else f"                row.{p} = ({t})cells[{i}];")
    w("            }")
    w("            w.Complete();")
    w("        }")
    w("        return stream.ToArray();")
    w("    }")
    w("")
    w("    internal override EvoReader Open(byte[] bytes, int mask, ParquetSchemaEvolutionOptions? evolution, RowReaderOptions options)")
    w(f"        => new {n}Reader(bytes, mask, evolution, options);")
    w("")
    w("    internal override int[] ReadColumnar(byte[] bytes, bool strict)")
    w("    {")
    w("        using var reader = Schema.CreateReader(new MemoryStream(bytes, writable: false), new Plank.Reading.Logical.ParquetReaderOptions { Strict = strict });")
    w("        var seqs = new List<int>();")
    w("        foreach (var group in reader.RowGroups)")
    w("            foreach (var buffer in group.Column<int>(Schema.LeafColumns[0]))")
    w("                seqs.AddRange(buffer.Values.ToArray());")
    w("        return [.. seqs];")
    w("    }")
    w("}")
    w("")
    w(f"sealed class {n}Reader : EvoReader")
    w("{")
    w(f"    readonly {n}.RowReader _reader;")
    w("    readonly int _mask;")
    w(f"    internal {n}Reader(byte[] bytes, int mask, ParquetSchemaEvolutionOptions? evolution, RowReaderOptions options)")
    w("    {")
    w("        _mask = mask;")
    w(f"        _reader = {n}.CreateRowReader(new MemoryStream(bytes, writable: false), Project(mask), options, evolution);")
    w("    }")
    w("    static " + n + ".Projection Project(int mask)")
    w("    {")
    w(f"        var p = {n}.Projection.None;")
    for i, (prop, _, _) in enumerate(cols):
        w(f"        if ((mask & {1 << i}) != 0) p |= {n}.Projection.{prop};")
    w("        return p;")
    w("    }")
    w("    internal override bool MoveNext() => _reader.MoveNext();")
    w("    internal override void Reset(byte[] bytes, int mask, ParquetSchemaEvolutionOptions? evolution)")
    w("        => _reader.Reset(new MemoryStream(bytes, writable: false), Project(mask), evolution);")
    w("    internal override string[] Current(int mask)")
    w("    {")
    w("        var r = _reader.Current;")
    w("        var cells = new List<string>();")
    for i, (prop, t, _) in enumerate(cols):
        w(f"        if ((mask & {1 << i}) != 0) cells.Add(EvoCanon.Of(r.{prop}));")
    w("        return [.. cells];")
    w("    }")
    w("    public override void Dispose() => _reader.Dispose();")
    w("}")
    w("")
w("static class EvoClasses")
w("{")
w("    internal static readonly EvoClass[] All = [" + ", ".join(f"new {n}Evo()" for _, n in names) + "];")
w("}")
print("\n".join(out))
