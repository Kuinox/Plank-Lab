#!/usr/bin/env python3
"""Join the reflected public surface (Plank.Fuzzing.ApiSurface TSV) with the cobertura reports of
fuzz/coverage-all.sh.  Usage: api-surface-join.py api.tsv fuzz/coverage/all > fuzz/notes/api-surface.md
A member is "reached" when any method with the same type, name and parameter count has a covered line
in any target (W=writer R=reader M=merger) and any ISA tier.  Overloads are matched by parameter count."""
import sys, re, glob, os, collections
import xml.etree.ElementTree as ET
tsv, covdir = sys.argv[1], sys.argv[2]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def nparams(sig):
    s = sig.strip()[1:-1] if sig.startswith('(') else sig
    if not s: return 0
    d = 0; n = 1
    for c in s:
        if c in '<[': d += 1
        elif c in '>]': d -= 1
        elif c == ',' and d == 0: n += 1
    return n
hits = collections.defaultdict(set)  # (type,name,n) -> targets
total = {}
for f in glob.glob(covdir + '/*.cobertura.xml'):
    tgt = os.path.basename(f)[0].upper()
    for cl in ET.parse(f).getroot().iter('class'):
        cn = cl.get('name').split('/<')[0]
        for m in cl.iter('method'):
            n = nparams(m.get('signature'))
            k = (cn.replace('/', '.').replace('+', '.'), m.get('name'), n)
            total[k] = True
            if any(int(l.get('hits')) > 0 for l in m.iter('line')): hits[k].add(tgt)
# nested lambdas/local functions are attributed to the declaring class via the regexp above, not to the method: also treat '<Name>g__' as the method
harness = ''.join(open(p, errors='ignore').read() for p in glob.glob(root + '/Plank.Fuzzing/*.cs'))
rows = []
for line in open(tsv):
    a, kind, typ, mem, sig = line.rstrip('\n').split('\t')
    if kind in ('type', 'enum') or a != 'Plank': 
        rows.append((a, kind, typ, mem, sig, None)); continue
    t = typ.replace('+', '.')
    names = [mem]
    if kind == 'prop':
        names = (['get_' + mem] if ' get' in sig else []) + (['set_' + mem] if ' set' in sig else [])
        n = 0
    elif kind == 'ctor': names = ['.ctor']; n = nparams(sig)
    else: n = nparams(sig.split('):')[0] + ')')
    if kind == 'prop':
        got = set()
        for nm in names:
            for k, v in hits.items():
                if k[0] == t and k[1] == nm: got |= v
        known = any(k[0] == t and k[1] in names for k in total)
    else:
        got = hits.get((t, mem if kind != 'ctor' else '.ctor', n), set())
        known = (t, mem if kind != 'ctor' else '.ctor', n) in total
    rows.append((a, kind, typ, mem, sig, (''.join(sorted(got)), known)))
refname = lambda mem: len(re.findall(r'\b' + re.escape(mem) + r'\b', harness))
out = []
cnt = collections.Counter()
by_type = collections.defaultdict(list)
for a, kind, typ, mem, sig, st in rows:
    if st is None: continue
    by_type[(a, typ)].append((kind, mem, sig, st))
out.append('# Plank public API surface x fuzz coverage (generated)\n')
out.append('Generated by `Plank.Fuzzing.ApiSurface` (reflection over Plank.dll and the SourceGen output compiled into Plank.Fuzzing) joined with '
           '`fuzz/coverage-all.sh` cobertura by `fuzz/api-surface-join.py`.\n')
out.append('Status: **unreached** = no covered line in any target/ISA tier (W=writer, R=reader, M=merger columns list who reached it); '
           '**reached** = covered; `refs` = number of textual references to the member name in `Plank.Fuzzing/*.cs` (0 = harness never names it, so any coverage is incidental). '
           'Whether the arguments are fuzzer-chosen is a manual judgement, see "Route review" below.\n')
for (a, typ), ms in sorted(by_type.items()):
    for kind, mem, sig, (got, known) in ms:
        s = 'reached' if got else ('unreached' if known else 'no-code-map')
        cnt[s] += 1
        if kind == 'prop': cnt['prop-' + s] += 1
out.append('## Summary\n')
out.append('| status | members |\n|---|---|')
for k, v in sorted(cnt.items()): out.append(f'| {k} | {v} |')
out.append('\n(`no-code-map` = no cobertura entry: abstract/interface/delegate members, trivial inlined or compiler-generated.)\n')
tc = collections.Counter()
for (a, typ), ms in by_type.items():
    for kind, mem, sig, (got, known) in ms: tc[typ] += 1
out.append('## Public types in Plank.dll\n')
for line in open(tsv):
    a, kind, typ, mem, sig = line.rstrip('\n').split('\t')
    if kind == 'type' and a == 'Plank': out.append(f'- `{typ}` ({mem}{" "+sig if sig else ""})')
out.append('\n## Members\n')
out.append('| type | kind | member | signature | status | W/R/M | refs |\n|---|---|---|---|---|---|---|')
for (a, typ), ms in sorted(by_type.items()):
    for kind, mem, sig, (got, known) in ms:
        s = 'reached' if got else ('unreached' if known else 'no-code-map')
        out.append(f'| {typ.split(".")[-1]} | {kind} | `{mem}` | `{sig.replace("System.","").replace("Plank.","")[:110]}` | {s} | {got} | {refname(mem)} |')
gen = [r for r in rows if r[0] == 'Plank.Fuzzing']
out.append('\n## SourceGen output (compiled into Plank.Fuzzing)\n')
gt = collections.defaultdict(lambda: collections.Counter())
for a, kind, typ, mem, sig, st in gen:
    if kind == 'type': continue
    gt[typ][mem] += 1
out.append('| generated type | members (name x overloads) |\n|---|---|')
for typ, c in sorted(gt.items()):
    out.append(f'| {typ.split(".")[-1]} | ' + ', '.join(f'{m}x{n}' if n > 1 else m for m, n in sorted(c.items()))[:400] + ' |')
print('\n'.join(out))
